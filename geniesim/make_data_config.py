#!/usr/bin/env python3
"""Write an XR-1 Hydra data config for converted Genie Sim episodes.

    python geniesim/make_data_config.py \
        --name geniesim_instruction \
        --paths /path/to/instruction_xr1 \
        --norm  /path/to/instruction_xr1_norm.json \
        --batch-size 32

XR-1 reads normalization statistics inline from the data config (see
configs/data/load_washer.yaml), so they are pasted in here rather than
referenced. Regenerate whenever the statistics are recomputed -- a stale config
silently normalizes with the old ones.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

XR1 = Path(__file__).resolve().parents[1] / "xr1"


def rows(a) -> str:
    return "\n".join(f"      - [{', '.join(repr(round(float(v), 6)) for v in r)}]" for r in a)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--name", required=True, help="config name -> configs/data/<name>.yaml")
    ap.add_argument("--paths", nargs="+", required=True, help="episode JSON directories")
    ap.add_argument("--norm", required=True, help="output of tools/compute_normalize.py")
    ap.add_argument("--batch-size", type=int, required=True, help="per GPU")
    ap.add_argument("--action-length", type=int, default=30)
    args = ap.parse_args()

    n = json.load(open(args.norm))
    for k, shape in (("mean", (args.action_length, 60)), ("std", (args.action_length, 60)),
                     ("q01", (1, 60)), ("q99", (1, 60))):
        got = (len(n[k]), len(n[k][0]))
        if got != shape:
            raise SystemExit(f"{k}: shape {got}, expected {shape}")

    paths = "\n".join(f"      - {p}" for p in args.paths)
    text = f"""# @package _global_
# Generated by geniesim/make_data_config.py from {args.norm}. Do not hand-edit
# the statistics; regenerate instead.

data:
  type: BaseDataModule
  params:
    type: json
    max_steps: ${{trainer.max_steps}}
    train_datasets:
      batch_size: {args.batch_size}
      action_length: {args.action_length}
      paths:
{paths}
      mean:
{rows(n["mean"])}
      std:
{rows(n["std"])}
      q01:
{rows(n["q01"])}
      q99:
{rows(n["q99"])}
"""
    out = XR1 / "configs" / "data" / f"{args.name}.yaml"
    out.write_text(text)
    print(f"wrote {out}  (batch {args.batch_size}/GPU, {len(args.paths)} path(s))")


if __name__ == "__main__":
    main()
